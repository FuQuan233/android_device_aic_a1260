#!/usr/bin/env python3
"""Package locally extracted Mali r8p0 DSOs with private dependency names.

Input is a read-only extraction of the owner's firmware, not a downloaded blob.
No device flashing or network access is performed. Public Bionic/libc++/log and
VNDK loading APIs remain supplied by the current Android build.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import struct
import subprocess

parser = argparse.ArgumentParser()
parser.add_argument("stock", type=Path, help="directory containing extracted lib/")
parser.add_argument("destination", type=Path, help="vendor/aic/a1260")
parser.add_argument("--patchelf", required=True)
parser.add_argument("--devinfo-atag", type=Path, required=True,
                    help="same device's original chosen/atag,devinfo backup")
args = parser.parse_args()
source = args.stock / "lib"
out = args.destination
out.mkdir(parents=True, exist_ok=True)
(out / "proprietary").mkdir(exist_ok=True)

# Convert this device's preserved ATAG to the old binary dev_info sysfs ABI:
# count followed by efuse words. Do not invent efuse values for another board.
tag = args.devinfo_atag.read_bytes()
if len(tag) < 12 or len(tag) % 4:
    parser.error("invalid devinfo ATAG length")
words = struct.unpack("<" + "I" * (len(tag) // 4), tag)
if (words[0] != len(words) or words[1] != 0x41000804 or
        words[-1] != len(words) - 3 or not 21 <= words[-1] <= 64 or
        words[22] != 0x6580):
    parser.error("expected this MT6580 device's complete original devinfo ATAG")
devinfo = struct.pack("<I", words[-1]) + tag[8:-4]
(out / "proprietary" / "mt6580-devinfo.bin").write_bytes(devinfo)

# These Android 8 libraries have private platform interfaces or global names
# shared with modern mapper/HWC. Rename each SONAME and all internal references.
exclude = {"libc++.so", "libvndksupport.so"}
inputs = {p.name: p for p in sorted(source.glob("*.so")) if p.name not in exclude}
inputs["libGLES_mali.so"] = source / "egl/libGLES_mali.so"
names = {name: "liba1260_stock_" + re.sub(r"[^A-Za-z0-9_]", "_", name[:-3].removeprefix("lib")) + ".so"
         for name in inputs}
names["libGLES_mali.so"] = "libGLES_mali.so"
modules = []
manifest = []
for original, path in inputs.items():
    name = names[original]
    dest = out / "proprietary" / name
    shutil.copyfile(path, dest)
    if original == "libmtk_drvb.so":
        old = b"/sys/bus/platform/drivers/dev_info/dev_info\0"
        new = b"/vendor/etc/mt6580-devinfo.bin\0"
        data = dest.read_bytes()
        if data.count(old) != 1:
            parser.error("unsupported libmtk_drvb: original dev_info path is not unique")
        # Adapt only the filename, keeping the original validation and error
        # handling. Fixed-size replacement preserves every code/data address.
        dest.write_bytes(data.replace(old, new.ljust(len(old), b"\0")))
    subprocess.run([args.patchelf, "--set-soname", name, str(dest)], check=True)
    needed = subprocess.check_output([args.patchelf, "--print-needed", str(dest)], text=True).splitlines()
    for dep in needed:
        if dep in names:
            subprocess.run([args.patchelf, "--replace-needed", dep, names[dep], str(dest)], check=True)
    module = name[:-3]
    modules.append(module)
    manifest.append({"source": str(path), "source_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                     "installed": "lib/" + ("egl/" if original == "libGLES_mali.so" else "") + name,
                     "module": module})

bp = ['// Generated by device/aic/a1260/tools/prepare_stock_mali.py.',
      '// Owner-supplied proprietary files remain local; do not redistribute.',
      'soong_namespace {}', '']
for item in manifest:
    bp += ['cc_prebuilt_library_shared {', f'    name: "{item["module"]}",',
           f'    srcs: ["proprietary/{item["module"]}.so"],',
           '    vendor: true,', '    compile_multilib: "32",',
           '    strip: { none: true },', '    check_elf_files: false,',
           '    prefer: true,']
    if item['module'] == 'libGLES_mali':
        bp.append('    relative_install_path: "egl",')
    bp += ['}', '']
(out / 'Android.bp').write_text('\n'.join(bp))
(out / 'mali-vendor.mk').write_text('# Generated local proprietary Mali package list.\n'
    'PRODUCT_SOONG_NAMESPACES += vendor/aic/a1260\n'
    'PRODUCT_PACKAGES += \\\n    ' + ' \\\n    '.join(modules) + '\n')
with (out / 'mali-vendor.mk').open('a') as mk:
    mk.write('PRODUCT_COPY_FILES += '
             'vendor/aic/a1260/proprietary/mt6580-devinfo.bin:'
             '$(TARGET_COPY_OUT_VENDOR)/etc/mt6580-devinfo.bin\n')
manifest.append({"source": str(args.devinfo_atag),
                 "source_sha256": hashlib.sha256(tag).hexdigest(),
                 "installed": "etc/mt6580-devinfo.bin", "words": words[-1],
                 "description": "Same-device efuses, converted to the legacy dev_info ABI"})
(out / 'mali-manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
print(f'Packaged {len(modules)} original DSOs and same-device devinfo into {out}')
